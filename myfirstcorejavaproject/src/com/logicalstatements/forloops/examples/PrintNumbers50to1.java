package com.logicalstatements.forloops.examples;

public class PrintNumbers50to1 {

		public static void main(String[] args) {
			System.out.println("Main Method Started!!");
			
			for(int i = 50; i > 0; i--) {
				System.out.print(i + " ");
			} 
			System.out.println("Main Method Ended!!");
		}
}
